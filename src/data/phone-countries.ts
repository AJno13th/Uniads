export function getPhoneCountryByIso(iso: string): PhoneCountry | undefined {
  return phoneCountries.find((c) => c.iso === iso);
}

/**
 * Build E.164-style phone (+447…) from country dial code + national number.
 * Strips a leading 0 from the national part (common UK/local format).
 */
export function composeInternationalPhone(
  countryCode: string,
  nationalNumber: string
): string | null {
  const cc = countryCode.replace(/\D/g, "");
  let national = nationalNumber.replace(/\D/g, "");
  if (!cc || !national) return null;

  if (national.startsWith(cc) && national.length > cc.length + 6) {
    return `+${national}`;
  }
  if (national.startsWith("00") && national.length > 8) {
    return `+${national.slice(2)}`;
  }

  if (national.startsWith("0")) national = national.slice(1);
  if (!national) return null;

  return `+${cc}${national}`;
}

/** Best-effort split of a stored phone into iso + dial code + national number. */
export function splitInternationalPhone(phone: string): {
  iso: string;
  country: string;
  national: string;
} {
  let digits = phone.trim().replace(/[^\d+]/g, "");
  if (digits.startsWith("00")) digits = digits.slice(2);
  if (digits.startsWith("+")) digits = digits.slice(1);
  digits = digits.replace(/\D/g, "");

  const gb = phoneCountries.find((x) => x.iso === "GB") ?? {
    iso: "GB",
    code: "44",
    label: "United Kingdom",
    flag: "🇬🇧",
  };

  if (!digits) {
    return { iso: gb.iso, country: gb.code, national: "" };
  }

  if (digits.startsWith("0")) {
    return { iso: gb.iso, country: gb.code, national: digits };
  }

  const sorted = [...phoneCountries].sort(
    (a, b) => b.code.length - a.code.length
  );
  for (const c of sorted) {
    if (digits.startsWith(c.code) && digits.length >= c.code.length + 6) {
      if (c.code === "44") {
        return {
          iso: gb.iso,
          country: gb.code,
          national: digits.slice(gb.code.length),
        };
      }
      if (c.code === "1") {
        const us = phoneCountries.find((x) => x.iso === "US");
        if (us) {
          return {
            iso: us.iso,
            country: us.code,
            national: digits.slice(1),
          };
        }
      }
      return {
        iso: c.iso,
        country: c.code,
        national: digits.slice(c.code.length),
      };
    }
  }

  return { iso: gb.iso, country: gb.code, national: digits };
}
